import type { Tokens } from "./tokens";

export type Format = "css" | "ts";

/** First line of every exported file; check skips files that carry it. */
export const EXPORT_MARK = "generated by gusteau export";

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

/** Names for the type scale, relative to the body step: xs, sm, body, md, lg, xl, 2xl, … */
export function typeNames(t: Tokens["type"]): string[] {
  const at = Math.max(0, t.scale.indexOf(t.body));
  return t.scale.map((_, i) => {
    const d = i - at;
    if (d === 0) return "body";
    if (d < 0) return d === -1 ? "sm" : `${d === -2 ? "" : -d - 1}xs`;
    return ["md", "lg", "xl"][d - 1] ?? `${d - 2}xl`;
  });
}

/** Token values as CSS custom properties, flat and named the way code refers to them. */
export function cssVars(t: Tokens): [string, string][] {
  const px = (n: number) => `${n}px`;
  const names = typeNames(t.type);
  return [
    ...Object.entries(t.color).map(([k, v]) => [`--color-${kebab(k)}`, v] as [string, string]),
    ...Object.entries(t.font).map(([k, v]) => [`--font-${k}`, `"${v}"`] as [string, string]),
    ...t.type.scale.map((v, i) => [`--type-${names[i]}`, px(v)] as [string, string]),
    ["--leading", String(t.type.leading)],
    ["--leading-tight", String(t.type.leadingTight)],
    ...t.space.map((v, i) => [`--space-${i + 1}`, px(v)] as [string, string]),
    ...Object.entries(t.radius).map(([k, v]) => [`--radius-${k}`, px(v)] as [string, string]),
    ["--duration-fast", `${t.motion.fast}ms`],
    ["--duration-base", `${t.motion.base}ms`],
    ["--duration-slow", `${t.motion.slow}ms`],
    ["--easing", t.motion.easing],
    ["--target", px(t.target)],
  ];
}

export function exportTokens(t: Tokens, format: Format): string {
  if (format === "css")
    return `/* ${EXPORT_MARK} from .gusteau/tokens.json; edit the tokens, not this file */\n:root {\n${cssVars(t).map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;
  return `// ${EXPORT_MARK} from .gusteau/tokens.json; edit the tokens, not this file\nexport const tokens = ${JSON.stringify(t, null, 2)} as const;\n\nexport default tokens;\n`;
}
